"""Per-upload inference configs.

The model resolves its input from configs/inference.yaml, not from a command
argument, and that file pins the video path together with a SHA-256 and the
patient/seizure identity. The pinning is a safety feature: it stops a recording
being scored against another recording's onset times, which would produce a
plausible-looking but meaningless result.

So rather than bypassing the check, this writes a fresh config per upload with
the provenance block filled in from the staged file and the details the
clinician entered. The model still verifies everything it verified before — it
is simply verifying against the new recording.

Nothing in the base config is mutated; each job gets its own file.
"""
from __future__ import annotations

import copy
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional

import yaml

GENERATED_DIRNAME = "generated"


class ConfigError(RuntimeError):
    pass


def load_base(model_repo: Path, base_name: str = "inference.yaml") -> dict[str, Any]:
    path = model_repo / "configs" / base_name
    if not path.exists():
        raise ConfigError(f"base config not found at {path}")
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as e:
        raise ConfigError(f"could not parse {path}: {e}") from e
    if not isinstance(data, dict):
        raise ConfigError(f"{path} is not a YAML mapping")
    return data


def build(
    base: dict[str, Any],
    *,
    video_path: Path,
    sha256: str,
    patient_id: Optional[str],
    seizure_id: Optional[str],
    seizure_type: Optional[str],
    job_id: str,
) -> dict[str, Any]:
    cfg = copy.deepcopy(base)
    data = cfg.setdefault("data", {})

    # Absolute, because the model runs with cwd set to its own repository and
    # the staged file lives outside it.
    data["video"] = str(video_path.resolve())

    prov = data.setdefault("video_provenance", {})
    prov["expected_sha256"] = sha256
    if patient_id:
        prov["patient_id"] = patient_id
    if seizure_id:
        prov["seizure_id"] = seizure_id
    if seizure_type:
        prov["seizure_type"] = seizure_type
    # The recording came through the dashboard, not from the dataset tree.
    prov["upstream_path"] = f"uploaded via dashboard (job {job_id})"
    prov["source"] = "dashboard upload"

    # Never let a generated config switch the model into a training mode.
    cfg.setdefault("training", {})["enabled"] = False
    cfg.setdefault("testing", {})["mode"] = "unimodal"

    return cfg


def write(cfg: dict[str, Any], model_repo: Path, job_id: str) -> Path:
    """Write beside the base config so repo-relative paths inside it still resolve."""
    out_dir = model_repo / "configs" / GENERATED_DIRNAME
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"job_{job_id}.yaml"

    header = (
        "# Generated by the SeizureAI dashboard - do not edit.\n"
        f"# {datetime.now(timezone.utc).isoformat(timespec='seconds')}\n"
        "# Derived from configs/inference.yaml with the video and provenance\n"
        "# fields replaced for one uploaded recording.\n\n"
    )
    path.write_text(header + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True),
                    encoding="utf-8")
    return path


def relative_to_repo(path: Path, model_repo: Path) -> str:
    """The CLI runs with cwd = model_repo, so pass it a repo-relative path."""
    try:
        return str(path.resolve().relative_to(model_repo.resolve())).replace("\\", "/")
    except ValueError:
        return str(path.resolve())